def area(a, b):
    '''
    Receive:
        a (int/float): rectangle length
        b (int/float): rectangle width
    Return:
        rectangle area (int/float): S = a * b 
    '''
    return a * b 

def perimeter(a, b):
    '''
    Receive:
        a (int/float): rectangle length
        b (int/float): rectangle width
    Return:
        rectangle perimeter (int/float): P = a + a + b + b = (a + b)*2
    '''
    return (a + b)*2 
