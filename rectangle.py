def area(a, b):
    '''
    Receive:
        a (float): rectangle length
        b (float): rectangle width
    Return:
        rectangle area (float): S = a * b 
    '''
    return a * b 

def perimeter(a, b):
    '''
    Receive:
        a (float): rectangle length
        b (float): rectangle width
    Return:
        rectangle perimeter (float): P = a + a + b + b = (a + b)*2
    '''
    return (a + b)*2 
