def area(a):
    '''
    Receive:
        a (int/float): square side
    Return:
        square area (int/float): S = a * a = a^2 
    '''
    return a * a


def perimeter(a):
    '''
    Receive:
        a (int/float): square side
    Return:
        square perimeter (int/float): P = a + a + a + a = a * 4 
    '''
    return 4 * a
